import json
import requests

data = requests.get("https://cdn.jsdelivr.net/npm/emojibase-data/en/data.json").json()
data.sort(key = lambda x: 2 if x['label'].startswith("flag: ") else 1 if x['label'].startswith('regional indicator') else 0)

print(r"""// Generated by gen/emojis_to_table.py
package nz.felle.messageasebetter;

import androidx.annotation.NonNull;

import java.util.List;

public class Emojis {
	public record Emoji(
		@NonNull String label,
		@NonNull String text
	) {}

	public static final @NonNull List<Emoji> EMOJIS = List.of(""", end = '')

first = True
for emoji in data:
	label = json.dumps(emoji['label'])
	string = json.dumps(emoji['emoji'])
	if not first:
		print(",", end='')
	print(f"\n\t\tnew Emoji({label}, {string})", end='')
	first = False
print(r""");
}""")